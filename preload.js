const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('buddy', {
  getState: () => ipcRenderer.invoke('state:get'),
  setState: (d) => ipcRenderer.send('state:set', d),
  move: (dir) => ipcRenderer.send('move', dir),
  media: (k) => ipcRenderer.send('media', k),
  openSpotify: (uri) => ipcRenderer.send('open-spotify', uri),
  volume: (o) => ipcRenderer.send('volume', o),
  onVolume: (cb) => ipcRenderer.on('volume', (_, d) => cb(d)),
  ttsStream: (o) => ipcRenderer.invoke('tts-stream', o),
  ttsCancel: (id) => ipcRenderer.send('tts-cancel', id),
  onTtsChunk: (cb) => ipcRenderer.on('tts-chunk', (_, d) => cb(d)),
  ttsRender: (o) => ipcRenderer.invoke('tts-render', o),
  ttsVoices: () => ipcRenderer.invoke('tts-voices'),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragMove: () => ipcRenderer.send('drag-move'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  voiceListen: () => ipcRenderer.send('voice-listen'),
  ensureVoiceModel: (model) => ipcRenderer.invoke('voice-ensure-model', model),
  voiceModelExists: (model) => ipcRenderer.invoke('voice-model-exists', model),
  aiAsk: (args) => ipcRenderer.invoke('ai-ask', args),
  aiHasKey: () => ipcRenderer.invoke('ai-has-key'),
  aiSetKey: (key) => ipcRenderer.invoke('ai-set-key', key),
  onVoiceStart: (cb) => ipcRenderer.on('voice-start', () => cb()),
  onVoiceModelProgress: (cb) => ipcRenderer.on('voice-model-progress', (_, pct) => cb(pct)),
  hide: () => ipcRenderer.send('hide'),
  quit: () => ipcRenderer.send('quit'),
  focusWindow: () => ipcRenderer.send('focus-window'),
  onForeground: (cb) => ipcRenderer.on('foreground', (_, d) => cb(d)),
  onSpotify: (cb) => ipcRenderer.on('spotify', (_, t) => cb(t)),
  onOpenCommand: (cb) => ipcRenderer.on('open-command', () => cb()),
});
